/// CLI command for zero-configuration deployment
pub async fn execute_zero_config_deployment() -> Result<()> {
    let mut deployment = ZeroConfigDeployment::new();

    let duration = deployment.rapid_bootstrap().await?;

    let summary = deployment.get_deployment_summary();

    println!("🎉 Zero-configuration deployment completed successfully!");
    println!("⏱️ Total time: {duration:?}");
    println!(
        "🖥️ System: {} cores, {} GB RAM, {} GB storage",
        summary.system_info.cpu.cores,
        summary.system_info.memory.total_bytes / 1024 / 1024 / 1024,
        summary.system_info.storage.total_bytes / 1024 / 1024 / 1024
    );
    println!("🚀 Services deployed: {}", summary.services_deployed);
    println!("✅ Health status: {}", summary.health_status);

    // Save configuration for future use
    let config_json = serde_json::to_string_pretty(&summary.config)?;
    tokio::fs::write("toadstool-auto-config.json", config_json).await?;

    println!("💾 Configuration saved to toadstool-auto-config.json");

    Ok(())
}
