    /// Discover ToadStool peers
    async fn discover_toadstool_peers(&self) -> Result<Vec<ServiceEndpoint>> {
        debug!("Discovering ToadStool peers");

        // Network scan for ToadStool instances
        let mut peers = Vec::new();

        // Try common ToadStool ports
        let ports = vec![5000, 5001, 5002];

        for port in ports {
            let endpoint = format!("http://localhost:{port}");
            if let Ok(service) = self.check_service_endpoint(&endpoint, "toadstool").await {
                peers.push(service);
            }
        }

        Ok(peers)
    }

    /// Check if a service endpoint is available
    async fn check_service_endpoint(
        &self,
        endpoint: &str,
        service_name: &str,
    ) -> Result<ServiceEndpoint> {
        // Simple HTTP check
        let client = reqwest::Client::new();
        let response = client
            .get(endpoint)
            .timeout(Duration::from_secs(2))
            .send()
            .await
            .context("Failed to connect to service")?;

        if response.status().is_success() {
            Ok(ServiceEndpoint {
                name: service_name.to_string(),
                endpoint: endpoint.to_string(),
                version: "1.0.0".to_string(),
                status: "online".to_string(),
                auth_required: false,
                discovered_at: Utc::now(),
            })
        } else {
            anyhow::bail!("Service endpoint returned error status")
        }
    }

    /// Generate biome configuration
    async fn generate_biome_config(&self) -> Result<BiomeConfig> {
        debug!("Generating biome configuration");

        let resources = BiomeResources {
            cpu_limit: (self.system_info.cpu.cores as f64 * 0.8).max(1.0),
            memory_limit: format!(
                "{}MB",
                self.system_info.memory.total_bytes / 1024 / 1024 * 80 / 100
            ),
            storage_limit: format!(
                "{}GB",
                self.system_info.storage.total_bytes / 1024 / 1024 / 1024 * 50 / 100
            ),
            gpu_limit: if self.system_info.gpu.count > 0 {
                Some(self.system_info.gpu.count)
            } else {
                None
            },
        };

        Ok(BiomeConfig {
            name: "auto-generated-biome".to_string(),
            version: "1.0.0".to_string(),
            description: "Automatically generated biome configuration".to_string(),
            resources,
        })
    }

    /// Generate runtime configuration
    async fn generate_runtime_config(&self) -> Result<RuntimeConfig> {
        debug!("Generating runtime configuration");

        let mut preferred_runtimes = vec!["native".to_string(), "wasm".to_string()];

        let container_runtime = if self.system_info.container_runtime.docker {
            preferred_runtimes.push("container".to_string());
            "docker".to_string()
        } else if self.system_info.container_runtime.podman {
            preferred_runtimes.push("container".to_string());
            "podman".to_string()
        } else {
            "none".to_string()
        };

        let gpu_runtime = if self.system_info.gpu.cuda {
            preferred_runtimes.push("gpu".to_string());
            Some("cuda".to_string())
        } else {
            None
        };

        Ok(RuntimeConfig {
            preferred_runtimes,
            container_runtime,
            wasm_runtime: "wasmtime".to_string(),
            gpu_runtime,
        })
    }

