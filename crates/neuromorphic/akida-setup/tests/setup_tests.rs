fn test_device_node_patterns() {
    let patterns = vec!["/dev/akida*", "/dev/akd1500_*"];

    for pattern in &patterns {
        assert!(pattern.starts_with("/dev/"));
        assert!(pattern.contains('*'), "Pattern should include wildcard");
    }
}

/// Test module name extraction
#[test]
fn test_module_name() {
    let module_path = "/path/to/akida-pcie.ko";
    let path = Path::new(module_path);
    let file_name = path.file_name().unwrap().to_str().unwrap();

    assert_eq!(file_name, "akida-pcie.ko");
    assert!(file_name.ends_with(".ko"));

    // Module name for lsmod check
    let module_name = "akida_pcie"; // Note: dash becomes underscore in kernel
    assert!(
        !module_name.contains('-'),
        "Module name in kernel uses underscores"
    );
}

/// Test vendor/device ID constants
#[test]
fn test_akida_pci_ids() {
    let vendor_id = "1e7c";
    let device_id = "bca1";

    // Vendor ID: Brainchip
    assert_eq!(vendor_id.len(), 4);
    assert!(vendor_id.chars().all(|c| c.is_ascii_hexdigit()));

    // Device ID: Akida
    assert_eq!(device_id.len(), 4);
    assert!(device_id.chars().all(|c| c.is_ascii_hexdigit()));

    // lspci format
    let lspci_id = format!("{vendor_id}:{device_id}");
    assert_eq!(lspci_id, "1e7c:bca1");
}

/// Test permission mode values
#[test]
fn test_permission_modes() {
    let mode_666: u32 = 0o666;

    // Verify mode bits
    let owner_rw = mode_666 & 0o700;
    let group_rw = mode_666 & 0o070;
    let other_rw = mode_666 & 0o007;

    assert_eq!(owner_rw, 0o600, "Owner should have rw");
    assert_eq!(group_rw, 0o060, "Group should have rw");
    assert_eq!(other_rw, 0o006, "Other should have rw");
}

/// Test lspci output parsing logic
#[test]
fn test_lspci_output_parsing() {
    // Simulated lspci output
    let lspci_output = "a1:00.0 Co-processor: Brainchip Inc. Device bca1";

    // Parse first word as PCIe address
    let pcie_addr = lspci_output.split_whitespace().next().unwrap();
    assert_eq!(pcie_addr, "a1:00.0");

    // Full address with domain
    let full_addr = format!("0000:{pcie_addr}");
    assert_eq!(full_addr, "0000:a1:00.0");
}

/// Test multiple device output parsing
#[test]
fn test_multiple_devices_parsing() {
    let lspci_output = "\
a1:00.0 Co-processor: Brainchip Inc. Device bca1
a2:00.0 Co-processor: Brainchip Inc. Device bca1
";

    let devices: Vec<String> = lspci_output
        .lines()
        .filter_map(|line| {
            line.split_whitespace()
                .next()
                .map(|addr| format!("0000:{addr}"))
        })
        .collect();

    assert_eq!(devices.len(), 2);
    assert_eq!(devices[0], "0000:a1:00.0");
    assert_eq!(devices[1], "0000:a2:00.0");
}

