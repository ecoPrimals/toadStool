/// Test UDEV rules content format
#[test]
fn test_udev_rules_format() {
    let rules_content = r#"# Akida PCIe device permissions
# Auto-generated by akida-setup
KERNEL=="akida[0-9]*", MODE="0666"
KERNEL=="akd1500_[0-9]*", MODE="0666"

# PCIe resource access for userspace drivers
SUBSYSTEM=="pci", ATTR{vendor}=="0x1e7c", ATTR{device}=="0xbca1", \
  RUN+="/bin/chmod 666 /sys/bus/pci/devices/%k/resource*", \
  RUN+="/bin/chmod 666 /sys/bus/pci/devices/%k/enable"
"#;

    // Verify rules content is valid
    assert!(rules_content.contains("KERNEL=="));
    assert!(rules_content.contains("MODE="));
    assert!(rules_content.contains("0x1e7c")); // Akida vendor ID
    assert!(rules_content.contains("0xbca1")); // Akida device ID
    assert!(rules_content.contains("SUBSYSTEM==\"pci\""));
}

/// Test `PCIe` address format validation
#[test]
fn test_pcie_address_format() {
    // Valid PCIe addresses
    let valid_addresses = vec![
        "0000:a1:00.0",
        "0000:00:1f.0",
        "0000:02:00.0",
        "0001:03:00.1",
    ];

    for addr in valid_addresses {
        // Basic format check: domain:bus:device.function
        let parts: Vec<&str> = addr.split(':').collect();
        assert_eq!(
            parts.len(),
            3,
            "PCIe address should have 3 colon-separated parts"
        );

        // Domain should be 4 hex digits
        assert_eq!(parts[0].len(), 4);
        assert!(parts[0].chars().all(|c| c.is_ascii_hexdigit()));

        // Bus should be 2 hex digits
        assert_eq!(parts[1].len(), 2);
        assert!(parts[1].chars().all(|c| c.is_ascii_hexdigit()));

        // Device.function
        let dev_func: Vec<&str> = parts[2].split('.').collect();
        assert_eq!(dev_func.len(), 2);
    }
}

/// Test sysfs path construction
#[test]
fn test_sysfs_path_construction() {
    let pcie_address = "0000:a1:00.0";
    let expected_enable_path = format!("/sys/bus/pci/devices/{pcie_address}/enable");
    let expected_resource_path = format!("/sys/bus/pci/devices/{pcie_address}/resource0");

    assert_eq!(
        expected_enable_path,
        "/sys/bus/pci/devices/0000:a1:00.0/enable"
    );
    assert_eq!(
        expected_resource_path,
        "/sys/bus/pci/devices/0000:a1:00.0/resource0"
    );
}

/// Test glob pattern for device nodes
